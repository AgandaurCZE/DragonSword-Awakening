"""Generate real GitHub Pages entry files for clean Beta URLs.

Run after index.html or SITE.routes/HEROES changes. --check verifies without writing.
Every entry is the same shell; its relative base locates the shared assets and scripts.
"""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
MARKER = '<!-- Generated by tools/build_routes.py. Edit the root index.html instead. -->\n'


def entries():
    data = json.loads((ROOT / 'data.json').read_text())
    site = data['SITE']
    paths = set(site['routes'].values()) | set(site['toolRoutes'].values()) | {'dungeons'}
    paths.update(h['name'] for h in data['HEROES'])
    paths.discard('')
    shell = (ROOT / 'index.html').read_text()
    for route in sorted(paths):
        if any(p in ('', '.', '..') for p in route.split('/')):
            raise ValueError(f'Invalid route: {route}')
        base = '../' * len(route.split('/'))
        yield ROOT / route / 'index.html', MARKER + shell.replace('<base href="./">', f'<base href="{base}">', 1)


def main():
    check = '--check' in sys.argv
    bad = []
    generated = list(entries())
    for path, html in generated:
        if check:
            if not path.exists() or path.read_text() != html:
                bad.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(html)
    expected = {p for p, _ in generated}
    for path in ROOT.glob('**/index.html'):
        if '.git' in path.parts or path in expected or path == ROOT / 'index.html':
            continue
        if path.read_text().startswith(MARKER):
            if check:
                bad.append(f'{path.relative_to(ROOT)} (obsolete)')
            else:
                path.unlink()
    if bad:
        print('Route entries out of date. Run python3 tools/build_routes.py:\n' + '\n'.join(bad))
        return 1
    print(f'Route entries OK: {len(generated)} clean URLs.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
